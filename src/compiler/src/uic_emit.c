#include "uic_internal.h"

#include <stdarg.h>
#include <stdio.h>
#include <string.h>

#define UIC_EMIT_INITIAL_CAPACITY 4096U
#define UIC_EMIT_HARD_LIMIT (32U * 1024U * 1024U)

typedef struct UicEmitBuffer
{
  char *bytes;
  uint64_t length;
  uint64_t capacity;
  const GwUiCompilerAllocator *allocator;
  GwUiCompilerErrorCode error;
} UicEmitBuffer;

static int uic_grow(UicEmitBuffer *buffer, uint64_t needed)
{
  uint64_t capacity = buffer->capacity == 0U ? UIC_EMIT_INITIAL_CAPACITY : buffer->capacity;
  char *grown;
  if (needed <= buffer->capacity)
    return 1;
  while (capacity < needed)
  {
    if (capacity > UIC_EMIT_HARD_LIMIT / 2U)
    {
      capacity = UIC_EMIT_HARD_LIMIT;
      break;
    }
    capacity *= 2U;
  }
  if (needed > UIC_EMIT_HARD_LIMIT || capacity < needed)
  {
    buffer->error = GW_UIC_ERROR_LIMIT;
    return 0;
  }
  grown = (char *)uic_allocate(buffer->allocator, capacity);
  if (grown == NULL)
  {
    buffer->error = GW_UIC_ERROR_ALLOCATION;
    return 0;
  }
  if (buffer->length != 0U)
    memcpy(grown, buffer->bytes, (size_t)buffer->length);
  uic_deallocate(buffer->allocator, buffer->bytes);
  buffer->bytes = grown;
  buffer->capacity = capacity;
  return 1;
}

static int uic_append(UicEmitBuffer *buffer, const char *format, ...)
{
  va_list args;
  va_list measure;
  int written;
  uint64_t needed;
  va_start(args, format);
  va_copy(measure, args);
  written = vsnprintf(NULL, 0U, format, measure);
  va_end(measure);
  if (written < 0)
  {
    va_end(args);
    return 0;
  }
  needed = buffer->length + (uint64_t)written + 1U;
  if (needed < buffer->length || !uic_grow(buffer, needed))
  {
    va_end(args);
    return 0;
  }
  written = vsnprintf(buffer->bytes + buffer->length, (size_t)(buffer->capacity - buffer->length),
                      format, args);
  va_end(args);
  if (written < 0 || (uint64_t)written >= buffer->capacity - buffer->length)
    return 0;
  buffer->length += (uint64_t)written;
  return 1;
}

static void uic_upper(const UicString *input, char *output, uint32_t capacity)
{
  uint32_t index;
  for (index = 0U; index < input->length && index + 1U < capacity; ++index)
    output[index] = input->bytes[index] >= 'a' && input->bytes[index] <= 'z'
                        ? (char)(input->bytes[index] - 'a' + 'A')
                        : input->bytes[index];
  output[index] = '\0';
}

int uic_emit_tree(const UicModel *model, const GwUiCompilerAllocator *allocator,
                  GwUiCompilerResult *result)
{
  UicEmitBuffer header;
  UicEmitBuffer source;
  char app[64];
  char child_ref[96];
  char action_ref[96];
  uint32_t index;
  uic_upper(model->application_name, app, (uint32_t)sizeof(app));
  (void)snprintf(child_ref, sizeof(child_ref), "gw_%s_children", model->application_name->bytes);
  (void)snprintf(action_ref, sizeof(action_ref), "gw_%s_actions", model->application_name->bytes);
  header = (UicEmitBuffer){NULL, 0U, 0U, allocator, GW_UIC_ERROR_ALLOCATION};
  source = (UicEmitBuffer){NULL, 0U, 0U, allocator, GW_UIC_ERROR_ALLOCATION};
  if (!uic_append(&header,
                  "/* Generated by Glyphweld. Do not edit. */\n#ifndef GW_%s_UI_H\n#define "
                  "GW_%s_UI_H\n#include <stdint.h>\n#include \"glyphweld/gw_ui.h\"\n#define "
                  "GW_UI_SCHEMA_VERSION 1U\n#define GW_UI_COMPILER_FORMAT_VERSION 2U\n#define "
                  "GW_%s_APPLICATION %uU\n",
                  app, app, app, model->application_id))
    goto fail;
  for (index = 0U; index < model->node_count; ++index)
  {
    char name[64];
    uic_upper(model->nodes[index].name, name, sizeof(name));
    if (!uic_append(&header, "#define GW_%s_NODE_%s %uU\n", app, name,
                    model->nodes[index].stable_id))
      goto fail;
  }
  for (index = 0U; index < model->action_count; ++index)
  {
    char name[64];
    uic_upper(model->actions[index].name, name, sizeof(name));
    if (!uic_append(&header, "#define GW_%s_ACTION_%s %uU\n", app, name,
                    model->actions[index].stable_id))
      goto fail;
  }
  if (!uic_append(&header, "extern const GwUiTreeDesc gw_%s_ui_tree;\n#endif\n",
                  model->application_name->bytes))
    goto fail;
  if (!uic_append(&source, "/* Generated by Glyphweld. Do not edit. */\n#include \"%s_ui.h\"\n",
                  model->application_name->bytes))
    goto fail;
  for (index = 0U; index < model->node_count; ++index)
    if (model->nodes[index].text != NULL)
    {
      uint32_t byte;
      if (!uic_append(&source, "static const char gw_%s_text_%u[] = {",
                      model->application_name->bytes, index))
        goto fail;
      for (byte = 0U; byte < model->nodes[index].text->length; ++byte)
        if (!uic_append(&source, "%uU,", (uint32_t)(uint8_t)model->nodes[index].text->bytes[byte]))
          goto fail;
      if (!uic_append(&source, "0U};\n"))
        goto fail;
    }
  if (!uic_append(&source, "static const GwUiTreeNodeDesc gw_%s_nodes[] = {\n",
                  model->application_name->bytes))
    goto fail;
  for (index = 0U; index < model->node_count; ++index)
  {
    const UicModelNode *node = &model->nodes[index];
    if (node->text == NULL)
    {
      if (!uic_append(&source,
                      "{(uint32_t)sizeof(GwUiTreeNodeDesc),{(uint32_t)sizeof(GwNodeDesc),%uU,%uU,%"
                      "uU,{NULL,0U},%d,%d,%uU,%d,%uU,%uU,%d,%d,%uU,%d,%uU},%uU,%uU},\n",
                      node->stable_id, node->action_id, node->kind, node->preferred_width,
                      node->preferred_height, node->grow, node->gap, node->background,
                      node->foreground, node->minimum_width, node->minimum_height, node->shrink,
                      node->padding, node->text_overflow, node->child_offset, node->child_count))
        goto fail;
    }
    else if (!uic_append(
                 &source,
                 "{(uint32_t)sizeof(GwUiTreeNodeDesc),{(uint32_t)sizeof(GwNodeDesc),%uU,%"
                 "uU,%uU,{gw_%s_text_%u,%uU},%d,%d,%uU,%d,%uU,%uU,%d,%d,%uU,%d,%uU},%uU,%uU},\n",
                 node->stable_id, node->action_id, node->kind, model->application_name->bytes,
                 index, node->text->length, node->preferred_width, node->preferred_height,
                 node->grow, node->gap, node->background, node->foreground, node->minimum_width,
                 node->minimum_height, node->shrink, node->padding, node->text_overflow,
                 node->child_offset, node->child_count))
      goto fail;
  }
  if (model->child_count != 0U)
  {
    if (!uic_append(&source, "};\nstatic const uint32_t gw_%s_children[] = {",
                    model->application_name->bytes))
      goto fail;
    for (index = 0U; index < model->child_count; ++index)
      if (!uic_append(&source, "%uU,", model->child_indices[index]))
        goto fail;
    if (!uic_append(&source, "};\n"))
      goto fail;
  }
  else if (!uic_append(&source, "};\n"))
    goto fail;
  if (model->action_count != 0U)
  {
    if (!uic_append(&source, "static const GwId gw_%s_actions[] = {",
                    model->application_name->bytes))
      goto fail;
    for (index = 0U; index < model->action_count; ++index)
      if (!uic_append(&source, "%uU,", model->actions[index].stable_id))
        goto fail;
    if (!uic_append(&source, "};\n"))
      goto fail;
  }
  if (!uic_append(&source,
                  "const GwUiTreeDesc gw_%s_ui_tree = "
                  "{(uint32_t)sizeof(GwUiTreeDesc),gw_%s_nodes,%uU,%s,%uU,%s,%uU};\n",
                  model->application_name->bytes, model->application_name->bytes, model->node_count,
                  model->child_count == 0U ? "NULL" : child_ref, model->child_count,
                  model->action_count == 0U ? "NULL" : action_ref, model->action_count))
    goto fail;
  result->header_bytes = (uint8_t *)header.bytes;
  result->header_size = header.length;
  result->source_bytes = (uint8_t *)source.bytes;
  result->source_size = source.length;
  result->allocator = *allocator;
  result->_ownership_magic = GW_UIC_RESULT_MAGIC;
  return 1;
fail:
  uic_deallocate(allocator, header.bytes);
  uic_deallocate(allocator, source.bytes);
  uic_diagnostic(result,
                 header.error == GW_UIC_ERROR_LIMIT || source.error == GW_UIC_ERROR_LIMIT
                     ? GW_UIC_ERROR_LIMIT
                     : GW_UIC_ERROR_ALLOCATION,
                 (UicPosition){1U, 1U}, "$", NULL,
                 "generated output allocation or 32 MiB limit exceeded");
  return 0;
}
